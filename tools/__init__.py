# Вспомогательные модули конвейера конвертации:
#
#   preprocess.py       — препроцессор Markdown (рендерит блоки <diagram> в PNG)
#   markdown_mask.py    — маскирование кода и комментариев перед разбором Markdown
#   _diagram_worker.py  — изолированный подпроцесс для рендеринга одной диаграммы
#   _pipeline_worker.py — подпроцесс, в котором GUI запускает весь конвейер
#   install_pandoc.py   — проверка и установка pandoc и pandoc-crossref
#
# Модули tools не импортируют core на уровне модуля. Исключение —
# _pipeline_worker.py: он является точкой входа конвейера и импортирует core
# внутри функции, уже после настройки sys.path.
